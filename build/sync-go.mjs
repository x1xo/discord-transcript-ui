/**
 * Keeps the Go renderer in step with this build.
 *
 * The two libraries are coupled in exactly three places, and all three are
 * derived from this repository's build output:
 *
 *   1. the markup contract version (the package version);
 *   2. the pinned CDN URLs and Subresource Integrity hashes;
 *   3. the compact tag vocabulary (build/short-tags.mjs).
 *
 * Hand-copying those invited drift: every rebuild changes the SRI hashes,
 * because the version is baked into each artifact's banner. So the build writes
 * them out instead, into two files the Go side never edits by hand.
 *
 * Point DISCORD_TRANSCRIPT_GO_DIR somewhere else if the Go module is not checked
 * out next to this repository; if it is absent the build says so and carries on,
 * so this package still builds for consumers who only want the stylesheet.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const HEADER = (source) =>
	`// Code generated by build/sync-go.mjs from ${source}.\n// DO NOT EDIT: run \`npm run build\` in discord-transcript-ui to refresh.\n\npackage transcript\n`;

/**
 * Resolves the Go module directory, or null when it is not checked out.
 *
 * Handles both layouts: the Go module nested inside this repository (where it
 * lives today) and a sibling checkout, in case the two are ever split apart
 * again. DISCORD_TRANSCRIPT_GO_DIR wins over both.
 */
export function goModuleDir() {
	const candidates = [
		process.env.DISCORD_TRANSCRIPT_GO_DIR,
		join(root, 'discord-transcript-go'),
		join(root, '..', 'discord-transcript-go')
	].filter(Boolean);
	return candidates.find((dir) => existsSync(join(dir, 'go.mod'))) ?? null;
}

/**
 * The pinned version, CDN URLs and SRI hashes, straight from the manifest.
 *
 * @param {{version: string, urls: Record<string, Record<string, string>>, integrity: Record<string, string>}} manifest
 * @returns {string} Go source
 */
export function pinsSource(manifest) {
	const jsdelivr = (key) => manifest.urls[key].jsdelivr;
	const pins = [
		['DefaultCSSURL', jsdelivr('css')],
		['DefaultCSSIntegrity', manifest.integrity.css],
		['DefaultShortCSSURL', jsdelivr('cssShort')],
		['DefaultShortCSSIntegrity', manifest.integrity.cssShort],
		['DefaultScriptURL', jsdelivr('js')],
		['DefaultScriptIntegrity', manifest.integrity.js]
	];
	// Aligned exactly as gofmt would, so a rebuild is a no-op rather than a diff.
	const width = Math.max(...pins.map(([name]) => name.length));
	const lines = pins.map(([name, value]) => `\t${name}${' '.repeat(width - name.length)} = ${JSON.stringify(value)}`).join('\n');
	return `${HEADER("this repository's dist/manifest.json")}
// ContractVersion is the discord-transcript-ui release whose markup contract
// this module emits.
const ContractVersion = ${JSON.stringify(manifest.version)}

// Pinned jsDelivr URLs and Subresource Integrity hashes for ContractVersion.
// The stylesheet is all a transcript needs to render; the script adds optional
// extras (click-to-reveal spoilers, copy buttons, viewer-local timestamps).
const (
${lines}
)
`;
}

/**
 * The compact tag vocabulary as a Go map, keyed by the semantic element name
 * (the part after "discord-") so it matches how the renderer talks about tags.
 *
 * @param {Record<string, string>} shortTags from build/short-tags.mjs
 * @returns {string} Go source
 */
export function tagsSource(shortTags) {
	const entries = Object.entries(shortTags)
		.map(([long, short]) => [long.replace(/^discord-/, ''), short])
		.sort(([a], [b]) => a.localeCompare(b));
	const width = Math.max(...entries.map(([name]) => name.length + 2));
	const lines = entries
		.map(([name, short]) => `\t${JSON.stringify(name)}:${' '.repeat(width - name.length - 1)}${JSON.stringify(short)},`)
		.join('\n');
	return `${HEADER('build/short-tags.mjs')}
// shortTagNames maps each semantic element name to its compact tag. Keep this in
// step by rebuilding discord-transcript-ui, which regenerates this file.
var shortTagNames = map[string]string{
${lines}
}
`;
}

/**
 * Writes the generated files, or reports whether they are current in check mode.
 *
 * @param {{manifest: object, shortTags: Record<string, string>, check?: boolean}} options
 * @returns {{written: string[], stale: string[], skipped: boolean}}
 */
export function syncGo({ manifest, shortTags, check = false }) {
	const dir = goModuleDir();
	if (!dir) return { written: [], stale: [], skipped: true };

	const files = [
		['transcript/pins.go', pinsSource(manifest)],
		['transcript/tags_gen.go', tagsSource(shortTags)]
	];

	const written = [];
	const stale = [];
	for (const [relative, content] of files) {
		const path = join(dir, relative);
		const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
		if (current === content) continue;
		if (check) {
			stale.push(relative);
			continue;
		}
		writeFileSync(path, content);
		written.push(relative);
	}

	if (written.length) {
		// The generated Go must be gofmt-clean; format it when gofmt is available.
		try {
			execFileSync('gofmt', ['-w', ...written.map((relative) => join(dir, relative))], { stdio: 'ignore' });
		} catch {
			// gofmt is optional; the generated text is already formatted.
		}
		// Best effort: prove the generated package still compiles. The build must
		// keep working for people without a Go toolchain, so a failure warns
		// rather than stops the JS build.
		try {
			execFileSync('go', ['build', './...'], { cwd: dir, stdio: 'pipe' });
		} catch (error) {
			console.warn('  go   warning: the synced Go package did not compile:');
			console.warn(String(error.stderr ?? error.message).trim().split('\n').map((l) => `        ${l}`).join('\n'));
		}
	}
	return { written, stale, skipped: false };
}
